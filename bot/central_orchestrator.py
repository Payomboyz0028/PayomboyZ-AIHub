    @staticmethod

    def inspect_file_content(sample_text: str, filename: str) -> Dict[str, Any]:

        sample = sample_text or ""

        fn_lower = (filename or "").lower()

        is_script_ext = any(fn_lower.endswith(ext) for ext in [".lua", ".luau", ".txt", ".bin", ".json"])



        detected_engine = "unknown"

        has_signature = False



        for engine, signatures in OBFUSCATION_SIGNATURES:

            if any(sig in sample for sig in signatures):

                detected_engine = engine

                has_signature = True

                break



        if not has_signature and re.search(r"return\s*\(\s*function\s*\(\s*\.\.\.\s*\)\s*local\s+\w+\s*=\s*\{", sample[:5000]):

            detected_engine = "wearedevs"

            has_signature = True



        return {

            "is_script_ext": is_script_ext,

            "has_signature": has_signature,

            "detected_engine": detected_engine,

        }



