# -*- coding: utf-8 -*-
"""
=============================================================================
  ⚡ PAYOMBØYZ MULTI-MODAL CONTEXT & INTENT INGESTION ENGINE (MCI-ENGINE V15.0)
  Solves File Ingestion Hell:
    - Never blindly hijacks map dumps into obfuscator/deobfuscator modals
    - Distinguishes:
        1. GAME_DUMP (ReplicatedStorage / Workspace / Dex Dump) -> Ground Truth Context
        2. OBFUSCATED_SCRIPT (Luraph, Moonsec, Prometheus, etc.) -> Deobfuscator
        3. CLEAN_SCRIPT (Raw Lua/Luau script for edit/expansion/study)
        4. BINARY_TARGET (PE, DLL, APK, WASM, JS bundle) -> REA Engine
        5. DIRECT_PROMPT (Chat, synthesis request, question)
    - Accompanying text extraction & disambiguation
=============================================================================
"""

from __future__ import annotations
import re
import json
from dataclasses import dataclass, field
from typing import Dict, Any, List, Optional, Tuple


@dataclass
class IngestionResult:
    route_target: str          # "game_dump_synthesis", "deobfuscate", "obfuscate", "rea_reverse", "script_synthesis", "clean_refactor", "general_chat"
    confidence: float
    payload_type: str          # "game_dump", "obfuscated_vm", "clean_script", "binary_bundle", "none"
    detected_engine: str       # "luraph", "moonsec", "prometheus", "dex_dump", "replicated_storage", "none"
    ground_truth_contract: Optional[Dict[str, Any]] = None
    extracted_prompt: str = ""
    is_dedicated_channel: bool = False
    requires_user_modal: bool = False
    diagnostics: Dict[str, Any] = field(default_factory=dict)


class MCIIngestionEngine:
    """
    Authoritative Ingestion & Forensic Classifier for incoming Discord messages & payloads.
    """

    # Obfuscator Signatures
    OBF_SIGNATURES = [
        ("luraph", [r"LPH_", r"LPH_OBFUSCATED", r"\\76\\117\\114\\97\\112\\104", r"V=buffer", r"Luraph Script", r"Luraph"]),
        ("moonveil", [r"-- This script was generated using MoonVeil", r"moonveil\.cc", r"MoonVeil", r"\[0b10\]=0b11"]),
        ("moonsec", [r"IronBrew", r":::MoonSec:::", r"\.\.:::MoonSec::\.\.", r"bit\.bxor", r"BitXOR"]),
        ("prometheus", [r"wearedevs\.net", r"wearedevs\.net/obfuscator", r"Firsthub x Phoenixhub"]),
        ("twok", [r"2K PROTECTED SCRIPT", r"2K Local Security", r"2K Security", r"local _k1", r"local _k2"]),
        ("luast", [r"-- generated by luast", r"luast\.clv\.cloud"]),
        ("psu", [r"PSU_SECURITY", r"psu_obfuscator", r"psu_vm"]),
        ("generic_vm", [r"local\s+v\d+\s*=\s*\{.*bit32", r"string\.byte\(.*string\.char", r"loadstring\(\s*game:HttpGet"])
    ]

    # Map Dump Signatures (Cobalt, Dark Dex, SimpleSpy, ReplicatedStorage Dumps)
    DUMP_PATTERNS = [
        r"ReplicatedStorage\.",
        r"\[(\"|')ReplicatedStorage(\"|')\]",
        r"game:GetService\((\"|')ReplicatedStorage(\"|')\)",
        r"game:GetService\((\"|')Workspace(\"|')\)",
        r"workspace\.",
        r"\[(\"|')Workspace(\"|')\]",
        r"\[(\"|')ClassName(\"|')\]\s*=\s*(\"|')RemoteEvent(\"|')",
        r"\[(\"|')ClassName(\"|')\]\s*=\s*(\"|')RemoteFunction(\"|')",
        r"\[(\"|')ClassName(\"|')\]\s*=\s*(\"|')BindableEvent(\"|')",
        r"\[(\"|')(Remotes?|Events?|Network|Packages|Knit|Services)(\"|')\]",
        r"Instance\.new\((\"|')(RemoteEvent|RemoteFunction|BindableEvent|BindableFunction|Folder|Model)(\"|')\)",
        r":WaitForChild\((\"|')(Remotes?|Events?|Network|Packages|Knit|Services)(\"|')\)",
        r":FireServer\(",
        r":InvokeServer\(",
        r"\"ClassName\":\s*\"RemoteEvent\"",
        r"\"ClassName\":\s*\"RemoteFunction\"",
        r"\"ClassName\":\s*\"Model\"",
        r"\"ClassName\":\s*\"Folder\"",
        r"\"Children\":\s*\[",
    ]

    # Script Creation Triggers in User Accompanying Text
    SCRIPT_CREATION_TRIGGERS = [
        "เขียน", "สร้าง", "ทำสคริป", "ทำสคริปต์", "เขียนสคริป", "เขียนสคริปต์",
        "ขอสคริป", "ขอสคริปต์", "ออโต้ฟาร์ม", "autofarm", "auto farm", "auto steal",
        "esp", "aimbot", "fly", "speed", "noclip", "teleport", "วาร์ป", "ตีมอน",
        "ฟาร์ม", "ขโมย", "ซื้อของ", "เปิดกล่อง", "สุ่มไข่", "killaura", "make script",
        "generate script", "build script", "create script", "write script"
    ]

    # Deobfuscation Triggers in User Accompanying Text
    DEOBF_TRIGGERS = [
        "แกะ", "ถอด", "ถอดรหัส", "deob", "deobf", "deobfuscate", "unobf", "unpack",
        "devirt", "devirtualize", "dump code", "แงะ", "แก้โค้ดที่ห่อ"
    ]

    # Obfuscation Triggers in User Accompanying Text
    OBF_TRIGGERS = [
        "ห่อ", "ล็อค", "เข้ารหัส", "obf", "obfuscate", "protect", "กันแกะ", "ออฟบัส", "ออบฟัส"
    ]

    @classmethod
    def inspect(
        cls,
        user_text: str = "",
        filename: str = "",
        content_bytes: bytes = b"",
        dedicated_mode: Optional[str] = None
    ) -> IngestionResult:
        """
        Main classifier entry point.
        """
        text = (user_text or "").strip()
        lowered_text = text.lower()
        fn = (filename or "").strip()
        fn_lower = fn.lower()
        content_len = len(content_bytes)

        # 1. Dedicated Drop Channel Overrides (If user dropped file into a dedicated tool channel)
        if dedicated_mode in ("deobfuscate", "obfuscate"):
            return IngestionResult(
                route_target=dedicated_mode,
                confidence=1.0,
                payload_type="obfuscated_vm" if dedicated_mode == "deobfuscate" else "clean_script",
                detected_engine="dedicated_channel",
                extracted_prompt=text,
                is_dedicated_channel=True,
                requires_user_modal=False,
                diagnostics={"reason": f"Dropped in dedicated {dedicated_mode} channel"}
            )

        # 2. Check for Native / Binary Files (.exe, .dll, .apk, .dex, .wasm, .js)
        if any(fn_lower.endswith(ext) for ext in [".exe", ".dll", ".sys", ".so", ".dylib", ".apk", ".dex", ".wasm", ".js", ".mjs"]):
            return IngestionResult(
                route_target="rea_reverse",
                confidence=0.98,
                payload_type="binary_bundle",
                detected_engine="rea_native",
                extracted_prompt=text,
                diagnostics={"reason": "Binary or Web bundle detected"}
            )

        # Decode sample text for inspection
        sample_str = ""
        if content_len > 0:
            sample_str = content_bytes[:65536].decode("utf-8", errors="replace")

        # 3. Calculate Obfuscation Score vs Map Dump Score vs Clean Script Score
        obf_engine = "none"
        obf_matches = 0
        for eng, sigs in cls.OBF_SIGNATURES:
            for s in sigs:
                if re.search(s, sample_str, re.IGNORECASE):
                    obf_engine = eng
                    obf_matches += 1
                    break
            if obf_engine != "none":
                break

        # Check dump pattern hits
        dump_matches = 0
        for dp in cls.DUMP_PATTERNS:
            if re.search(dp, sample_str, re.IGNORECASE):
                dump_matches += 1

        # Check JSON structure
        is_valid_json = False
        json_keys = set()
        if sample_str.strip().startswith("{") or sample_str.strip().startswith("["):
            try:
                parsed_json = json.loads(sample_str[:15000] + (sample_str[15000:].rsplit("}", 1)[0] + "}" if "}" in sample_str[15000:] else ""))
                if isinstance(parsed_json, dict):
                    is_valid_json = True
                    json_keys = set(parsed_json.keys())
            except Exception:
                pass

        is_dump_json = is_valid_json and bool({"ClassName", "Children", "Properties", "ReplicatedStorage", "Workspace", "PlaceId"} & json_keys)

        # 4. User Prompt Intent Signals
        has_script_trigger = any(t in lowered_text for t in cls.SCRIPT_CREATION_TRIGGERS)
        has_deobf_trigger = any(t in lowered_text for t in cls.DEOBF_TRIGGERS)
        has_obf_trigger = any(t in lowered_text for t in cls.OBF_TRIGGERS)
        has_dump_mention = any(t in lowered_text for t in ["dump", "ดัมพ์", "ดัมพ", "แมพดัมพ์", "map dump", "game dump", "ข้อมูลแมพ", "โครงสร้างแมพ"])

        # 5. Core Decision Matrix
        # Case A: Explicit Map Dump Detection (JSON dump or Luau table dump of game services)
        if (dump_matches >= 2 or is_dump_json or (dump_matches >= 1 and has_dump_mention)) and obf_engine == "none":
            # This is definitely a Map Dump!
            return IngestionResult(
                route_target="game_dump_synthesis",
                confidence=0.96,
                payload_type="game_dump",
                detected_engine="map_schema_dump",
                extracted_prompt=text if text else "วิเคราะห์ Remotes และโครงสร้างในแมพดัมพ์นี้เพื่อสร้างสคริปต์ Auto Farm / Exploits ตัวเต็ม",
                requires_user_modal=False,
                diagnostics={
                    "dump_matches": dump_matches,
                    "is_dump_json": is_dump_json,
                    "reason": "Clear ReplicatedStorage/Workspace dump structure"
                }
            )

        # Case B: Confirmed Obfuscated File
        if obf_engine != "none" or (has_deobf_trigger and content_len > 0):
            # If user explicitly asked to obfuscate, route to obf
            if has_obf_trigger:
                return IngestionResult(
                    route_target="obfuscate",
                    confidence=0.95,
                    payload_type="clean_script",
                    detected_engine="software_obfuscator",
                    extracted_prompt=text,
                    requires_user_modal=False
                )
            return IngestionResult(
                route_target="deobfuscate",
                confidence=0.98 if obf_engine != "none" else 0.85,
                payload_type="obfuscated_vm",
                detected_engine=obf_engine if obf_engine != "none" else "heuristic_obf",
                extracted_prompt=text,
                requires_user_modal=False,
                diagnostics={"obf_engine": obf_engine, "matches": obf_matches}
            )

        # Case C: Clean Lua/Luau script attached + User wants to build / edit / add features
        if content_len > 0 and fn_lower.endswith((".lua", ".luau", ".txt")):
            if has_obf_trigger:
                return IngestionResult(
                    route_target="obfuscate",
                    confidence=0.95,
                    payload_type="clean_script",
                    detected_engine="software_obfuscator",
                    extracted_prompt=text,
                    requires_user_modal=False
                )
            elif has_script_trigger or not has_deobf_trigger:
                # User gave a script and wants enhancements or auto-farm based on it!
                # NEVER block with SingleActionPromptView!
                return IngestionResult(
                    route_target="clean_refactor",
                    confidence=0.90,
                    payload_type="clean_script",
                    detected_engine="luau_source",
                    extracted_prompt=text if text else "ปรับปรุงและเขียนฟังก์ชั่นเพิ่มเติมให้สคริปต์นี้",
                    requires_user_modal=False,
                    diagnostics={"reason": "Clean script with request for synthesis/refactor"}
                )

        # Case D: Text Only — Script Synthesis or Q&A
        if has_script_trigger or "roblox.com/games" in lowered_text:
            return IngestionResult(
                route_target="script_synthesis",
                confidence=0.92,
                payload_type="none",
                detected_engine="multi_agent_factory",
                extracted_prompt=text,
                requires_user_modal=False
            )

        # Case E: General Peer Chat
        return IngestionResult(
            route_target="general_chat",
            confidence=0.80,
            payload_type="none",
            detected_engine="none",
            extracted_prompt=text,
            requires_user_modal=False
        )
