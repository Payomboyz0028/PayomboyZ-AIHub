def is_ironbrew_available() -> bool:
    """Checks if .NET runtime and IronBrew 2 compiled DLL exist."""
    if not IRONBREW_DLL.exists():
        return False
    try:
        res = subprocess.run(["dotnet", "--list-runtimes"], capture_output=True, text=True, timeout=5)
        return res.returncode == 0
    except Exception:
        return False


def obfuscate_with_ironbrew(
    source_code: str,
    options: Optional[Dict[str, Any]] = None
) -> str:
    """
    Obfuscates Lua/Luau source code using the PayomboyZ IronBrew 2 Virtualizer Fork.
    
    Args:
        source_code: Clean Lua 5.1 / Luau source code.
        options: Dictionary with settings:
            - control_flow (bool): Enable CFG flattening (default: True)
            - anti_tamper (bool): Inject PayomboyZ canary envelope (default: True)
            - timeout_sec (int): Maximum execution timeout in seconds (default: 30)
            
    Returns:
        Fully virtualized, runnable Lua 5.1 / Luau code.
    """
    options = options or {}
    timeout_sec = options.get("timeout_sec", 30)
    anti_tamper = options.get("anti_tamper", True)

    if not IRONBREW_DLL.exists():
        raise FileNotFoundError(f"IronBrew2 CLI DLL not found at: {IRONBREW_DLL}")

    # Create an isolated temporary workspace directory inside the IronBrew folder
    # Note: IronBrew CLI relies on relative paths (e.g. luac.exe, luajit.exe in cwd)
    job_id = f"job_{uuid.uuid4().hex[:12]}"
    job_dir = IRONBREW_DIR / f"temp_{job_id}"
    job_dir.mkdir(parents=True, exist_ok=True)

    input_file = job_dir / "input.lua"
    # Write source code with UTF-8 / Latin1 compatibility
    with open(input_file, "w", encoding="latin1", errors="replace") as f:
        f.write(source_code)

    try:
        # Run dotnet exec in IRONBREW_DIR so relative toolchain paths (luac.exe, luajit.exe) resolve
        cmd = [
            "dotnet", "exec",
            "--roll-forward", "LatestMajor",
            str(IRONBREW_DLL),
            str(input_file)
        ]

        result = subprocess.run(
            cmd,
            cwd=str(IRONBREW_DIR),
            capture_output=True,
            text=True,
            timeout=timeout_sec
        )

        out_file = IRONBREW_DIR / "out.lua"
        if result.returncode != 0 or not out_file.exists():
            err_msg = result.stderr.strip() or result.stdout.strip() or "Unknown IronBrew compilation error"
            raise RuntimeError(f"IronBrew2 Virtualizer failed (code {result.returncode}): {err_msg}")

        # Read generated bytecode VM
        with open(out_file, "r", encoding="latin1", errors="replace") as f:
            obf_code = f.read()

        # Clean out.lua immediately to prevent stale reads
        try:
            out_file.unlink()
        except Exception:
            pass

        # Post-processing: Enhance with PayomboyZ Luau compatibility & Anti-Tamper if requested
        if anti_tamper:
            final_code = f"{LUAU_COMPAT_HEADER}\n{obf_code}"
        else:
            final_code = obf_code

        return final_code

    finally:
        # Cleanup temporary job directory
        if job_dir.exists():
            shutil.rmtree(job_dir, ignore_errors=True)


